#!/usr/bin/env node
// Refresh full, mini and embedded fallback rows from one new-meta dataset.
import { readFile, writeFile, rename } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({ options: { input: { type: 'string' } } });
let rows;
if (values.input) rows = JSON.parse(await readFile(values.input, 'utf8'));
else {
  const response = await fetch('https://asset.rilaksekai.com/data/music_metas.json', { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`Music metas HTTP ${response.status}`);
  rows = await response.json();
}
const key = row => `${row.music_id}-${row.difficulty}`;
const byKey = new Map(rows.map(row => [key(row), row]));
if (!rows.length || byKey.size !== rows.length) throw new Error('Empty/duplicate meta dataset');
for (const row of rows) {
  for (const name of ['music_time','event_rate','base_score','base_score_auto','fever_score','fever_end_time','tap_count']) {
    if (!Number.isFinite(row[name]) || row[name] < 0) throw new Error(`Invalid ${key(row)} ${name}`);
  }
  for (const name of ['skill_score_solo','skill_score_auto','skill_score_multi',
    ...['skill_score_solo_inclusive','skill_score_multi_inclusive'].filter(name => row[name] !== undefined)]) {
    if (!Array.isArray(row[name]) || row[name].length !== 6 || row[name].some(n => !Number.isFinite(n) || n < 0)) throw new Error(`Invalid ${key(row)} ${name}`);
  }
}
const miniOld = JSON.parse(await readFile(path.join(root, 'public/music_metas_min.json'), 'utf8'));
const essentialSource = await readFile(path.join(root, 'src/data/essentialMusicMetas.js'), 'utf8');
const { ESSENTIAL_MUSIC_METAS } = await import(`data:text/javascript;base64,${Buffer.from(essentialSource).toString('base64')}`);
const subset = old => old.map(row => {
  const replacement = byKey.get(key(row));
  if (!replacement) throw new Error(`Missing fallback key ${key(row)}`);
  return replacement;
});
const mini = subset(miniOld), essential = subset(ESSENTIAL_MUSIC_METAS);
const outputs = [
  ['public/music_metas.json', JSON.stringify(rows)],
  ['src/data/music_metas.json', JSON.stringify(rows)],
  ['public/music_metas_min.json', JSON.stringify(mini)],
  ['src/data/essentialMusicMetas.js', '// Generated by scripts/update-music-metas.mjs from the new chart-derived meta dataset.\nexport const ESSENTIAL_MUSIC_METAS = '+JSON.stringify(essential, null, 2)+';'],
];
for (const [file, text] of outputs) {
  const target = path.join(root, file), temporary = `${target}.${process.pid}.tmp`;
  await writeFile(temporary, text+'\n');
  await rename(temporary, target);
}
console.log(JSON.stringify({ full: rows.length, mini: mini.length, essential: essential.length }));
